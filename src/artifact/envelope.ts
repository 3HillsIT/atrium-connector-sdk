// The two-layer envelope: one file that moves around, containing exactly
// `payload.tar.gz` and a detached `payload.sig`.
//
//   <id>-<version>.atrium.tar.gz
//   ├── payload.tar.gz     ← hashed and signed; unpacks into the Connector Store
//   │   ├── manifest.json
//   │   ├── ATRIUM-SIGNED.json
//   │   └── actions/*.js
//   └── payload.sig        ← a LIST of signatures, so a rotation can dual-sign
//
// Two layers exist because a file cannot contain its own hash — that is what
// reconciles "sign a digest document" with "one file moves around". The outer
// layer carries no trust of its own: nothing about it is signed, so a tampered
// outer layer simply fails the inner check.
//
// It does not remove the need for a hardened extractor. What it buys is that
// the only tar parsed before ANY signature has been checked is a two-entry
// flat read — a per-file content listing says nothing about tar headers, so
// symlinks, '..' and duplicate names have to be refused structurally.
//
// Binding: atrium's ADR-0007, the Connector Artifact format and store.

