// --- writing (publish) ---------------------------------------------------

export interface SignerKey {
  keyId: string;
  privateKey: CryptoKey;
}

export interface WriteEnvelopeParams {
  manifest: PublishedManifest;
  /**
   * Every payload file except manifest.json and ATRIUM-SIGNED.json, keyed by
   * payload-relative path — in practice `actions/<name>.js`. Both generated
   * files are written here rather than accepted from the caller, so the
   * listing and the manifest cannot disagree with what was actually packed.
   */
  files: Map<string, Uint8Array>;
  /**
   * Several means a dual-signed artifact for a rotation window. None writes
   * an UNSIGNED artifact: payload.sig carries the signed blob and no
   * signature line, which every opener refuses as `signature-missing` until a
   * signature is added to it (the SDK's `build`, then `sign`).
   */
  signers: SignerKey[];
  /** ISO 8601. Recorded in the signed blob; never enforced at verify time. */
  publishedAt: string;
}

export interface WrittenEnvelope {
  /** The bytes of `<id>-<version>.atrium.tar.gz`. */
  bytes: Uint8Array;
  fileName: string;
  /** payload.tar.gz's digest — the value recorded in the ledger and the connectors row. */
  payloadSha256: string;
}

export async function writeEnvelope(params: WriteEnvelopeParams): Promise<WrittenEnvelope> {
  // Publish runs the install path's own rules against its output, so an
  // artifact no Instance could open fails on the publishing machine instead of
  // at a customer's. Same reasoning as the publish ledger: move the refusal
  // upstream of the customer.
  assertPublishableIdentity(params.manifest.id, params.manifest.version);
  for (const action of params.manifest.actions) {
    assertSafeEntryName(action.bundle, 'The manifest');
  }

  const manifestBytes = utf8(JSON.stringify(params.manifest, null, 2) + '\n');
  const payloadFiles = new Map<string, Uint8Array>([[MANIFEST_FILE, manifestBytes]]);
  for (const [path, data] of params.files) {
    if (path === MANIFEST_FILE || path === LISTING_FILE) {
      throw new Error(`${path} is generated by writeEnvelope and must not be supplied.`);
    }
    assertSafeEntryName(path, 'The payload');
    payloadFiles.set(path, data);
  }
  for (const action of params.manifest.actions) {
    if (!payloadFiles.has(action.bundle)) {
      throw new Error(
        `Action "${action.name}" declares bundle "${action.bundle}", which is not among the ` +
          'files being published.',
      );
    }
  }

  const listing = await buildListing({
    id: params.manifest.id,
    version: params.manifest.version,
    files: payloadFiles,
  });
  const listingBytes = serializeListing(listing);
  payloadFiles.set(LISTING_FILE, listingBytes);

  // Sorted so the archive's entry order is a property of the content rather
  // than of a Map's insertion order.
  const sorted = [...payloadFiles.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const payload = gzip(writeTar(sorted.map(([name, data]) => ({ name, data }))));

  const blob: SignedBlob = {
    id: params.manifest.id,
    version: params.manifest.version,
    payloadSha256: await sha256Hex(payload),
    listingSha256: await sha256Hex(listingBytes),
    publishedAt: params.publishedAt,
  };
  const blobBytes = serializeBlob(blob);

  const signatures: ArtifactSignature[] = [];
  for (const signer of params.signers) {
    signatures.push(
      await signBlob({ blob: blobBytes, keyId: signer.keyId, privateKey: signer.privateKey }),
    );
  }

  const bytes = writeEnvelopeParts({
    payload,
    signature: serializeSignatureFile(signatures, blobBytes),
  });

  return {
    bytes,
    fileName: artifactFileName(params.manifest.id, params.manifest.version),
    payloadSha256: blob.payloadSha256,
  };
}

// --- adding a signature (the SDK's `sign`) -------------------------------

/** A key that signs an existing Artifact, with the public half its signature is checked against. */
export interface ArtifactSigner extends SignerKey {
  /** Base64 SPKI: the half the new signature must verify with. */
  publicKey: string;
}

export interface AddedSignature {
  /** The Artifact with the signature in its payload.sig; payload.tar.gz is the same bytes. */
  bytes: Uint8Array;
  /** The Artifact as the signer's key alone opens it: every check an Instance makes on Add. */
  opened: VerifiedArtifact;
  /** Every key id payload.sig names now, in its order, the signer's included. */
  signedBy: string[];
  /** True when payload.sig already had a signature by this key, which the new one replaced. */
  replaced: boolean;
}

/**
 * Adds one signature to an Artifact, unsigned (as `build` writes it) or
 * already signed (a rotation's second key). Only payload.sig changes: the
 * payload, its listing and the signed blob are the bytes they were, so the
 * payload digest an Instance records cannot move. A signature by the same key
 * id is replaced where it stood, never doubled.
 *
 * Then the result is opened with the signer's public half as the only ring
 * key, which checks the new signature and everything after it (payload
 * digest, listing, manifest) as an Instance's Add does. A signature that
 * doesn't verify (a private half that isn't the public half's) is refused as
 * `signature-invalid`, and nothing is returned to write.
 */
export async function addSignature(bytes: Uint8Array, signer: ArtifactSigner): Promise<AddedSignature> {
  const parts = readEnvelope(bytes);
  const file = parseSignatureFile(parts.signature, { allowUnsigned: true });
  const signature = await signBlob({
    blob: file.blobBytes,
    keyId: signer.keyId,
    privateKey: signer.privateKey,
  });

  const at = file.signatures.findIndex((line) => line.keyId === signer.keyId);
  const replaced = at !== -1;
  const signatures = replaced
    ? file.signatures.flatMap((line, index) =>
        line.keyId !== signer.keyId ? [line] : index === at ? [signature] : [],
      )
    : [...file.signatures, signature];

  const signed = writeEnvelopeParts({
    payload: parts.payload,
    signature: serializeSignatureFile(signatures, file.blobBytes),
  });

  let opened: VerifiedArtifact;
  try {
    opened = await openArtifact(signed, [
      { keyId: signer.keyId, alg: SIGNATURE_ALG, publicKey: signer.publicKey, comment: 'the signer' },
    ]);
  } catch (err) {
    if (err instanceof ConnectorArtifactError && err.code === 'signature-invalid') {
      throw artifactError(
        'signature-invalid',
        `The signature made with key ${signer.keyId} does not verify with that key's public half: ` +
          'the private half belongs to another key.',
        { keyId: signer.keyId },
      );
    }
    throw err;
  }
  return { bytes: signed, opened, signedBy: signatures.map((line) => line.keyId), replaced };
}

// --- the outer layer ----------------------------------------------------

export interface EnvelopeParts {
  payload: Uint8Array;
  signature: Uint8Array;
}

/**
 * The outer layer from its two parts: what `writeEnvelope` ends with, and
 * the inverse of `readEnvelope`. For a caller that changes payload.sig and
 * nothing else (adding a signature), so the payload's bytes, and with them
 * its digest, cannot move.
 */
export function writeEnvelopeParts(parts: EnvelopeParts): Uint8Array {
  return gzip(
    writeTar([
      { name: PAYLOAD_ENTRY, data: parts.payload },
      { name: SIGNATURE_ENTRY, data: parts.signature },
    ]),
  );
}

/**
 * Accepts exactly two flat regular files, named `payload.tar.gz` and
 * `payload.sig`, and nothing else. Deliberately narrow: this is the one tar
 * parsed before any signature has been checked, so the smaller the grammar the
 * smaller the pre-authentication attack surface.
 */
export function readEnvelope(bytes: Uint8Array): EnvelopeParts {
  // Bounded at two entries: an artifact with a third is refused on its header,
  // before the reader walks it. This is the one tar parsed with nothing
  // verified yet, so it refuses early rather than counting first.
  const entries = readTar(gunzip(bytes, 'The artifact'), 'The artifact', 2);

  if (entries.length !== 2) {
    throw artifactError(
      'envelope-malformed',
      `A Connector Artifact must contain exactly two files (${PAYLOAD_ENTRY} and ` +
        `${SIGNATURE_ENTRY}); this one contains ${entries.length}.`,
      { entryCount: String(entries.length) },
    );
  }

  const found = new Map<string, Uint8Array>();
  for (const entry of entries) {
    if (entry.typeflag !== '0') {
      throw artifactError(
        'envelope-malformed',
        `A Connector Artifact must contain only flat regular files; "${entry.name}" is not one.`,
        { path: entry.name, typeflag: entry.typeflag },
      );
    }
    if (entry.name !== PAYLOAD_ENTRY && entry.name !== SIGNATURE_ENTRY) {
      throw artifactError(
        'envelope-malformed',
        `A Connector Artifact must contain exactly ${PAYLOAD_ENTRY} and ${SIGNATURE_ENTRY}; ` +
          `it also contains "${entry.name}".`,
        { path: entry.name },
      );
    }
    if (found.has(entry.name)) {
      throw artifactError(
        'envelope-malformed',
        `A Connector Artifact contains "${entry.name}" twice.`,
        { path: entry.name },
      );
    }
    found.set(entry.name, entry.data);
  }

  const payload = found.get(PAYLOAD_ENTRY);
  if (!payload) {
    throw artifactError('envelope-malformed', `The artifact has no ${PAYLOAD_ENTRY}.`);
  }
  const signature = found.get(SIGNATURE_ENTRY);
  if (!signature) {
    throw artifactError('signature-missing', `The artifact has no ${SIGNATURE_ENTRY}.`);
  }
  return { payload, signature };
}

// --- the published manifest ---------------------------------------------

/**
 * Parses and checks a published manifest. `reading` picks the set it is held
 * to (see `ManifestReading`): an Artifact being Added must be manifest
 * version 3 and carry a `connection` block; a version already in the
 * Connector Volume is read at any version this Atrium reads, for what it is.
 */
export function parsePublishedManifest(
  data: Uint8Array | undefined,
  reading: ManifestReading = 'add',
): PublishedManifest {
  if (!data) {
    throw artifactError('manifest-invalid', `The artifact contains no ${MANIFEST_FILE}.`);
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(fromUtf8(data));
  } catch (err) {
    throw artifactError('manifest-invalid', `${MANIFEST_FILE} is not valid JSON.`, {
      reason: err instanceof Error ? err.message : String(err),
    });
  }

  const manifest = parsed as Partial<PublishedManifest>;
  if (manifest === null || typeof manifest !== 'object') {
    throw artifactError('manifest-invalid', `${MANIFEST_FILE} is not an object.`);
  }
  // Add's set first, so an Artifact too old to Add is refused naming the
  // version Add accepts, not the wider set a held version is read at.
  const manifestVersion = checkManifestVersion(manifest, reading);
  if (
    typeof manifest.id !== 'string' ||
    typeof manifest.displayName !== 'string' ||
    typeof manifest.version !== 'string' ||
    typeof manifest.connectorApiVersion !== 'number' ||
    !Array.isArray(manifest.actions)
  ) {
    throw artifactError(
      'manifest-invalid',
      `${MANIFEST_FILE} is missing one of { id, displayName, version, connectorApiVersion, actions }.`,
    );
  }
  // The Store path is built from id and version, so the install side needs the
  // same shape rules publish enforces — the extraction containment check
  // guards what happens *inside* a version directory, not which directory that
  // is.
  if (!CONNECTOR_ID_PATTERN.test(manifest.id)) {
    throw artifactError(
      'manifest-invalid',
      `${MANIFEST_FILE} declares an unusable connector id ("${manifest.id}").`,
      { id: manifest.id },
    );
  }
  if (!CONNECTOR_VERSION_PATTERN.test(manifest.version)) {
    throw artifactError(
      'manifest-invalid',
      `${MANIFEST_FILE} declares an unusable version ("${manifest.version}").`,
      { version: manifest.version },
    );
  }
  for (const action of manifest.actions) {
    if (typeof action?.name !== 'string' || typeof action?.bundle !== 'string') {
      throw artifactError(
        'manifest-invalid',
        `${MANIFEST_FILE} has an action without a name or a bundle path.`,
      );
    }
    // inputSchema is what supplies the MCP tool schema. Checking it here means
    // a malformed artifact is refused at the door rather than surfacing much
    // later as a broken Tool, which is the whole point of verifying on Add.
    if (
      typeof action.description !== 'string' ||
      action.inputSchema === null ||
      typeof action.inputSchema !== 'object' ||
      Array.isArray(action.inputSchema)
    ) {
      throw artifactError(
        'manifest-invalid',
        `${MANIFEST_FILE}'s action "${action.name}" is missing a description or an inputSchema ` +
          'object.',
        { action: action.name },
      );
    }
  }
  // The field is what version 3 announces, so a version-2 manifest carrying
  // it is not a version-2 manifest: refused rather than read either way.
  // `in`, not `!== undefined`: a key present with any value is the claim.
  if ('connection' in manifest && manifestVersion < CONNECTION_MANIFEST_VERSION) {
    throw artifactError(
      'manifest-invalid',
      `${MANIFEST_FILE} declares manifestVersion ${manifestVersion} but carries a ` +
        `connection block, which only manifestVersion ${CONNECTION_MANIFEST_VERSION} and later ` +
        'may declare.',
      { field: 'connection', manifestVersion: String(manifestVersion) },
    );
  }
  checkConnectionBlock(manifest, reading);
  return manifest as PublishedManifest;
}

/**
 * What each `ManifestReading` holds a manifest to: the versions it accepts,
 * the verb its refusal names, and whether the `connection` block must be
 * there. The one place the two readings differ.
 */
const MANIFEST_READINGS: Record<
  ManifestReading,
  { versions: readonly number[]; verb: string; requiresConnection: boolean }
> = {
  add: { versions: ADDABLE_MANIFEST_VERSIONS, verb: 'adds', requiresConnection: true },
  held: { versions: READABLE_MANIFEST_VERSIONS, verb: 'reads', requiresConnection: false },
};

/** Parsed once: Add requires the block, a held read checks it when present. */
function checkConnectionBlock(manifest: Partial<PublishedManifest>, reading: ManifestReading): void {
  if (MANIFEST_READINGS[reading].requiresConnection) {
    parseRequiredConnection(manifest.connection, MANIFEST_FILE);
  } else if ('connection' in manifest) {
    parseConnection(manifest.connection, MANIFEST_FILE);
  }
}

/**
 * What Add asks of a manifest beyond being readable: a version it accepts
 * (`ADDABLE_MANIFEST_VERSIONS`), and the `connection` block that version
 * requires. Throws the refusal Add gives. Exported so that `atrium connector
 * inspect`, which reads any readable Artifact, can report it as a finding
 * from the same rule rather than from a second copy of it.
 */
export function checkAddable(manifest: PublishedManifest): void {
  checkManifestVersion(manifest, 'add');
  checkConnectionBlock(manifest, 'add');
}

/**
 * The supported-set check, with ADR-0007's two remedies. Too new and too old
 * are different codes because the admin has to do opposite things: upgrade
 * the Instance, or go and get a newer build of the Connector.
 */
function checkManifestVersion(
  manifest: Partial<PublishedManifest>,
  reading: ManifestReading,
): ReadableManifestVersion {
  const { versions, verb } = MANIFEST_READINGS[reading];
  const declared = manifest.manifestVersion as unknown;
  if (typeof declared === 'number' && versions.includes(declared)) {
    return declared as ReadableManifestVersion;
  }

  const oldest = versions[0]!;
  const newest = versions[versions.length - 1]!;
  const named =
    typeof manifest.id === 'string' && typeof manifest.version === 'string'
      ? `${manifest.id}@${manifest.version}`
      : 'This Connector Artifact';
  const details = {
    manifestVersion: String(declared),
    supported: versions.join(','),
  };
  const situation =
    `${named} declares manifestVersion ${String(declared)}; ` +
    `this atrium Version ${verb} manifestVersion ${oldest === newest ? oldest : `${oldest}–${newest}`}.`;

  if (typeof declared !== 'number' || !Number.isInteger(declared)) {
    throw artifactError('manifest-invalid', `${situation} That is not a manifest version.`, details);
  }
  if (declared > newest) {
    throw artifactError(
      'manifest-too-new',
      `${situation} It was published for a newer atrium Version: update this Instance to add it.`,
      details,
    );
  }
  throw artifactError(
    'manifest-too-old',
    `${situation} It was published for an older atrium Version: obtain a newer build of this ` +
      'Connector Artifact.',
    details,
  );
}

// --- the whole verify path ----------------------------------------------

/**
 * Verify, unpack, check. In this order, and the order is the design:
 *
 *   1. Narrow two-entry read of the outer layer.
 *   2. Signature over the signed blob, against the ring.
 *   3. payload.tar.gz's digest against the digest the signature covers —
 *      only now is any of the payload trusted.
 *   4. Hardened extraction of the payload.
 *   5. ATRIUM-SIGNED.json's own digest, then exact set equality over
 *      everything else.
 *   6. The manifest, and that it agrees with the signed blob about id@version.
 *      Held to what Add accepts: every caller is about to Add, publish or
 *      self-check the Artifact.
 *
 * Nothing reaches the Connector Store from here — the caller decides where
 * verified files land.
 */
export async function openArtifact(
  bytes: Uint8Array,
  ring: RingKey[],
): Promise<VerifiedArtifact> {
  const parts = readEnvelope(bytes);
  const verification = await verifySignatureFile(parseSignatureFile(parts.signature), ring);
  const unpacked = await unpackSignedPayload(parts.payload, verification.blob);
  return { ...unpacked, keyIds: verification.keyIds, publishedAt: verification.blob.publishedAt };
}

/**
 * Steps 3–6 above, given a signed blob and the payload it claims to cover.
 *
 * Split out for atrium's `atrium connector inspect`, which reaches the same
 * checks by a different route: it treats an unknown signing key as something
 * to report rather than to refuse, and so cannot go through `openArtifact`.
 * Everything downstream of the signature is identical, and shared rather
 * than reimplemented so the two cannot drift about what a well-formed payload
 * is. Inspect reads with `held`, so an older Artifact is still shown for what
 * it is.
 *
 * Exported for that one reader. A caller reaching for it to Add something is
 * one skipping the signature, which is the one thing neither route does.
 */
export async function unpackSignedPayload(
  payload: Uint8Array,
  blob: SignedBlob,
  reading: ManifestReading = 'add',
): Promise<Omit<VerifiedArtifact, 'keyIds' | 'publishedAt'>> {
  const payloadSha256 = await sha256Hex(payload);
  if (!digestsEqual(payloadSha256, blob.payloadSha256)) {
    throw artifactError(
      'payload-digest-mismatch',
      'The artifact does not match its signature: it was altered or truncated in transit. ' +
        `Signed ${blob.payloadSha256}, received ${payloadSha256}.`,
      { expected: blob.payloadSha256, actual: payloadSha256 },
    );
  }

  const files = readSafeEntries(gunzip(payload, PAYLOAD_ENTRY), PAYLOAD_ENTRY);

  const listingBytes = files.get(LISTING_FILE);
  if (!listingBytes) {
    throw artifactError('listing-malformed', `The artifact contains no ${LISTING_FILE}.`);
  }
  const listingSha256 = await sha256Hex(listingBytes);
  if (!digestsEqual(listingSha256, blob.listingSha256)) {
    throw artifactError(
      'listing-digest-mismatch',
      `${LISTING_FILE} is not the hash listing that was signed.`,
      { expected: blob.listingSha256, actual: listingSha256 },
    );
  }

  const listing = parseListing(listingBytes);
  await checkListing(listing, files);

  const manifest = parsePublishedManifest(files.get(MANIFEST_FILE), reading);
  if (manifest.id !== blob.id || manifest.version !== blob.version) {
    throw artifactError(
      'version-mismatch',
      `The artifact declares ${manifest.id}@${manifest.version} but was signed as ` +
        `${blob.id}@${blob.version}.`,
      {
        declared: `${manifest.id}@${manifest.version}`,
        signed: `${blob.id}@${blob.version}`,
      },
    );
  }
  // ADR-0007 §6 says the manifest and the hash listing "agree by
  // construction". They do only because publish generates both — so the
  // install side checks it rather than assuming it. Without this, an artifact
  // with a dangling bundle path verifies clean and fails much later, when an
  // Action is loaded, where the reason is far harder to attribute.
  for (const action of manifest.actions) {
    if (!files.has(action.bundle)) {
      throw artifactError(
        'manifest-invalid',
        `Action "${action.name}" declares bundle "${action.bundle}", which the artifact does ` +
          'not contain.',
        { action: action.name, bundle: action.bundle },
      );
    }
  }

  if (listing.id !== manifest.id || listing.version !== manifest.version) {
    throw artifactError(
      'version-mismatch',
      `${LISTING_FILE} belongs to ${listing.id}@${listing.version} but the manifest declares ` +
        `${manifest.id}@${manifest.version}.`,
      {
        declared: `${manifest.id}@${manifest.version}`,
        signed: `${listing.id}@${listing.version}`,
      },
    );
  }

  return { manifest, listing, files, payloadSha256 };
}

/**
 * The filename convention as an assertion the verified manifest must match.
 *
 * This holds for a file an operator placed in the Drop Folder by hand, which
 * is why it is a refusal rather than a rename. It deliberately does NOT run on
 * the upload path — there the filename is *generated from* the verified
 * manifest, so it cannot mismatch by construction and the browser-supplied
 * name is error text only.
 */
export function checkArtifactFileName(fileName: string, manifest: PublishedManifest): void {
  const expected = artifactFileName(manifest.id, manifest.version);
  if (fileName !== expected) {
    throw artifactError(
      'filename-mismatch',
      `The file is named "${fileName}" but contains ${manifest.id}@${manifest.version}, which ` +
        `must be delivered as "${expected}".`,
      { fileName, expected },
    );
  }
}

/**
 * Parses `<id>-<version>.atrium.tar.gz` without opening the file — what a Drop
 * Folder scan matches on, and what lets an air-gapped operator see what they
 * have with `ls`.
 *
 * Both halves can contain dashes (`azure-devops`, `1.0.0-rc.1`), so neither
 * the first nor the last dash splits them. What does is that a version always
 * starts with a digit and matches semver: the split is the earliest dash whose
 * remainder is a whole version. A guess is all this is — the verified manifest
 * is the authority, and `checkArtifactFileName` compares the whole string.
 */
export function parseArtifactFileName(
  fileName: string,
): { id: string; version: string } | undefined {
  if (!fileName.endsWith(ARTIFACT_EXTENSION)) return undefined;
  const stem = fileName.slice(0, -ARTIFACT_EXTENSION.length);

  for (let dash = stem.indexOf('-'); dash !== -1; dash = stem.indexOf('-', dash + 1)) {
    const id = stem.slice(0, dash);
    const version = stem.slice(dash + 1);
    if (CONNECTOR_ID_PATTERN.test(id) && CONNECTOR_VERSION_PATTERN.test(version)) {
      return { id, version };
    }
  }
  return undefined;
}

/**
 * What publish refuses to emit. Not a taste question: an id or version
 * carrying a newline corrupts the line-oriented signed blob, and one carrying
 * a path separator or a dash-digit shape that re-splits differently produces a
 * filename no scan can read back.
 */
export function assertPublishableIdentity(id: string, version: string): void {
  if (!CONNECTOR_ID_PATTERN.test(id)) {
    throw new Error(
      `Connector id "${id}" cannot be published: ids must match ${CONNECTOR_ID_PATTERN}.`,
    );
  }
  if (!CONNECTOR_VERSION_PATTERN.test(version)) {
    throw new Error(
      `Connector version "${version}" cannot be published: versions must match ` +
        `${CONNECTOR_VERSION_PATTERN}.`,
    );
  }
  const parsed = parseArtifactFileName(artifactFileName(id, version));
  if (!parsed || parsed.id !== id || parsed.version !== version) {
    throw new Error(
      `${id}@${version} produces a filename that does not read back as ${id}@${version}. ` +
        'Choose an id that does not end in something version-shaped.',
    );
  }
}
